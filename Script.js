let currentLang = 'en';

function setLanguage(lang) {
    currentLang = lang;
    
    // Update direction and HTML language attributes
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;

    // Translate DOM elements
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // Update Language Dropdown Button Text
    document.getElementById('currentLang').textContent = translations[lang].lang_label;

    // Close language menu
    document.getElementById('langMenu').classList.remove('show');
}

document.addEventListener('DOMContentLoaded', () => {
    const langToggleBtn = document.getElementById('langToggleBtn');
    const langMenu = document.getElementById('langMenu');
    const menuBtn = document.getElementById('menuBtn');
    const navLinks = document.getElementById('navLinks');
    const form = document.getElementById('studentRegistrationForm');
    const formStatus = document.getElementById('formStatus');

    // Language Dropdown Toggle
    langToggleBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        langMenu.classList.toggle('show');
    });

    // Close Dropdown when clicking outside
    document.addEventListener('click', () => {
        langMenu.classList.remove('show');
    });

    // Mobile Menu Toggle
    menuBtn.addEventListener('click', () => {
        navLinks.classList.toggle('active');
    });

    // Registration Form Submission Handler
    form.addEventListener('submit', (e) => {
        e.preventDefault();

        const name = document.getElementById('fullName').value;
        const grade = document.getElementById('grade').value;

        formStatus.style.color = '#10b981'; // Success Green

        if (currentLang === 'am') {
            formStatus.textContent = `እናመሰግናለን ${name}! የክፍል ${grade} ምዝገባዎ በስኬት ተላክል።`;
        } else if (currentLang === 'ar') {
            formStatus.textContent = `شكراً لك ${name}! تم تقديم طلب التسجيل للصف ${grade} بنجاح.`;
        } else {
            formStatus.textContent = `Thank you, ${name}! Your registration for Grade ${grade} has been successfully submitted.`;
        }

        form.reset();
    });
});


